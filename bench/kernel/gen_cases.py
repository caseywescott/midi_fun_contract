#!/usr/bin/env python3
"""Writes src/cases.cairo: the case matrix (CASES, shared with run.py) as snforge tests."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
# (name, kind, species, sound_effects, drift_day). kind: 0 Sound Check, 1 genesis song,
# 2 named song (prefix 1, suffix 1), 3 Monthly Track Edition 3 of the species (seed fixed).
CASES = [
    ('check_1_fx0', 0, 1, 0, 0),
    ('check_64_fx0', 0, 64, 0, 0),
    ('check_64_fx1', 0, 64, 1, 0),
    ('song_21_fx0', 1, 21, 0, 0),
    ('song_1_fx0', 1, 1, 0, 0),
    ('song_32_fx0', 1, 32, 0, 0),
    ('song_68_fx0', 1, 68, 0, 0),
    ('song_44_fx3', 1, 44, 3, 0),
    ('song_32_fx3', 1, 32, 3, 0),
    ('named_44_fx0', 2, 44, 0, 0),
    ('edition_40_fx0', 3, 40, 0, 0),
    ('edition_40_fx3', 3, 40, 3, 0),
    ('drift_20_d2_fx0', 1, 20, 0, 2),
    ('drift_32_d40_fx3', 1, 32, 3, 40),
]
PROBE_SIZES = [0, 1024, 4096, 8192]

HEAD = '''//! GENERATED by gen_cases.py. Each test makes exactly one call to its measured entry point.
use beast_composer::composition::beast_v3_sound::PackableBeastV3;
use beast_composer::composition::genesis::{genesis_song_inputs, species_tier, species_type};
use beast_composer::composition::sound_check::sound_check_inputs;
use beast_composer::inputs::drift::DriftInputs;
use beast_composer::inputs::{ComposerInputs, EditionInputs, MusicIdentity};
use beast_contracts::pure_composer::{IBeastPureComposerDispatcher, IBeastPureComposerDispatcherTrait};
use core::poseidon::poseidon_hash_span;
use snforge_std::{ContractClassTrait, DeclareResultTrait, declare};
use starknet::ClassHash;
use crate::probes::{IKernelProbeDispatcher, IKernelProbeDispatcherTrait};

fn class(name: ByteArray) -> ClassHash {
    declare(name).unwrap().contract_class().class_hash
}

fn deploy(name: ByteArray) -> starknet::ContractAddress {
    let (a, _) = declare(name).unwrap().contract_class().deploy(@array![]).unwrap();
    a
}

fn digest<T, +Serde<T>, +Drop<T>>(v: @T) -> (u32, felt252) {
    let mut f: Array<felt252> = array![];
    v.serialize(ref f);
    (f.len(), poseidon_hash_span(f.span()))
}

fn inputs(kind: u8, sid: u64) -> ComposerInputs {
    let mut b = PackableBeastV3 {
        id: sid, prefix: 0, suffix: 0, level: 1, health: 100, shiny: 0, animated: 0,
        tier: species_tier(sid), beast_type: species_type(sid),
    };
    if kind == 0 {
        return ComposerInputs::SoundCheck(sound_check_inputs(b));
    }
    if kind == 3 {
        return ComposerInputs::Edition(
            EditionInputs {
                identity: MusicIdentity { source_species_id: sid.try_into().unwrap(), name_variant_id: 0 },
                edition: 3,
                seed: 0xfedcba9876543210,
            },
        );
    }
    if kind == 2 {
        b.prefix = 1;
        b.suffix = 1;
    }
    ComposerInputs::Song(genesis_song_inputs(b, b.prefix, b.suffix, 0, Option::None))
}

#[inline(never)]
fn run(case: u32, kind: u8, sid: u64, fx: u8, day: u64) {
    // The kernel is declared in every case (outside the measured call) so the harness is the same
    // for the baseline composer, which never calls it, and the candidate, which does.
    let kernel = class("MidiKernel");
    let x = inputs(kind, sid);
    let composer = IBeastPureComposerDispatcher { contract_address: deploy("BeastPureComposer") };
    let sound = if day == 0 {
        composer.compose(x, fx)
    } else {
        let d = DriftInputs {
            name_variant_id: 0, day, day_hash: 'day' + day.into(),
            week_hash: 'week' + ((day - 1) / 7).into(), month_hash: 'month' + ((day - 1) / 30).into(),
        };
        composer.compose_drift(x, fx, d)
    };
    verify(case, digest(@sound), sound.midi.len(), kernel);
}

#[cfg(feature: 'record')]
fn verify(case: u32, got: (u32, felt252), midi_len: u32, kernel: ClassHash) {
    let (n, h) = got;
    println!("KCASE case={} felts={} hash={} midi_len={} kernel={:?}", case, n, h, midi_len, kernel);
}
#[cfg(not(feature: 'record'))]
fn verify(case: u32, got: (u32, felt252), midi_len: u32, kernel: ClassHash) {
    assert(got == crate::expected::expected(case), 'KERNEL OUTPUT CHANGED');
}

fn probe() -> IKernelProbeDispatcher {
    IKernelProbeDispatcher { contract_address: deploy("KernelProbe") }
}
'''


def main():
    tests = []
    for i, (name, kind, sid, fx, day) in enumerate(CASES):
        tests.append(f'#[test]\nfn case_{i:02}_{name}() {{\n    run({i}, {kind}, {sid}, {fx}, {day});\n}}')
    tests.append('#[test]\nfn probe_noop() {\n    let s = class("Sink");\n    probe().noop(s);\n}')
    for n in PROBE_SIZES:
        tests.append(f'#[test]\nfn probe_build_{n}() {{\n    assert(probe().build({n}) == 4, \'build\');\n}}')
        tests.append(f'#[test]\nfn probe_take_{n}() {{\n    let s = class("Sink");\n'
                     f'    assert(probe().take(s, {n}) == 4, \'take\');\n}}')
        tests.append(f'#[test]\nfn probe_smf_local_{n}() {{\n    let p = probe();\n'
                     f'    let got = p.smf_local({n});\n'
                     f'    assert(got == midi::smf::smf_byte_array(1, 480, crate::probes::tracks_of({n}).span()), \'local\');\n}}')
        tests.append(f'#[test]\nfn probe_smf_kernel_{n}() {{\n    let k = class("MidiKernel");\n    let p = probe();\n'
                     f'    let got = p.smf_kernel(k, {n});\n'
                     f'    assert(got == midi::smf::smf_byte_array(1, 480, crate::probes::tracks_of({n}).span()), \'kernel\');\n}}')
    for n in PROBE_SIZES:
        tests.append(f'#[test]\nfn probe_build_felts_{n}() {{\n    assert(probe().build_felts({n}) == {n}, \'bf\');\n}}')
        tests.append(f'#[test]\nfn probe_ser_felts_{n}() {{\n    assert(probe().ser_felts({n}) == {n} + 1, \'sf\');\n}}')
        tests.append(f'#[test]\nfn probe_raw_felts_{n}() {{\n    let s = class("Sink");\n'
                     f'    assert(probe().raw_felts(s, {n}) == {n}, \'rf\');\n}}')
        tests.append(f'#[test]\nfn probe_take_felts_{n}() {{\n    let s = class("Sink");\n'
                     f'    assert(probe().take_felts(s, {n}) == {n}, \'tf\');\n}}')
    (HERE / 'src/cases.cairo').write_text(HEAD + '\n' + '\n\n'.join(tests) + '\n')


if __name__ == '__main__':
    main()
