#!/usr/bin/env python3
"""EXPERIMENT (exp/kernel-libcall): BeastPureComposer gas, with and without the MidiKernel boundary.

  python3 bench/kernel/run.py record --out snap.json   # baseline: print digests, write src/expected.cairo
  python3 bench/kernel/run.py run --out snap.json      # candidate: check digests, capture gas
  python3 bench/kernel/run.py compare base.json cand.json

Reuses bench/scripts/gas_bench.py's pinned tool resolution, snforge command and strict trace
parser. Set SCARB_TARGET_DIR (internal disk). A watchdog kills the run past --max-rss-gb.
"""
import argparse
import importlib.util
import json
import os
import re
import subprocess
import sys
import threading
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from gen_cases import CASES, PROBE_SIZES  # noqa: E402

spec = importlib.util.spec_from_file_location('gas_bench', HERE.parent / 'scripts/gas_bench.py')
gb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gb)
PREFIX = 'kernel_bench::cases::'


def tree_rss_bytes(pid):
    out = subprocess.run(['ps', '-axo', 'pid=,ppid=,rss='], capture_output=True, text=True).stdout
    kids, rss = {}, {}
    for line in out.split('\n'):
        f = line.split()
        if len(f) == 3:
            p, pp, r = map(int, f)
            kids.setdefault(pp, []).append(p)
            rss[p] = r * 1024
    total, stack = 0, [pid]
    while stack:
        q = stack.pop()
        total += rss.get(q, 0)
        stack.extend(kids.get(q, []))
    return total


def run_watched(cmd, env, log_path, max_rss):
    with open(log_path, 'w') as log:
        t0 = time.time()
        p = subprocess.Popen(cmd, cwd=HERE, env=env, stdout=log, stderr=subprocess.STDOUT)
        peak, killed = [0], [False]

        def watch():
            while p.poll() is None:
                r = tree_rss_bytes(p.pid)
                peak[0] = max(peak[0], r)
                if r > max_rss:
                    killed[0] = True
                    subprocess.run(['pkill', '-9', '-P', str(p.pid)])
                    p.kill()
                time.sleep(0.5)
        th = threading.Thread(target=watch, daemon=True)
        th.start()
        code = p.wait()
        th.join()
    if killed[0]:
        sys.exit(f'killed: process tree passed {max_rss / 2**30:.1f} GB')
    return code, round(time.time() - t0, 1), round(peak[0] / 2**20)


def classes():
    target = Path(os.environ['SCARB_TARGET_DIR']) / 'dev'
    out = {}
    for name in ['BeastPureComposer', 'MidiKernel']:
        p = target / f'kernel_bench_{name}.compiled_contract_class.json'
        if p.exists():
            j = json.loads(p.read_text())
            out[name] = dict(casm_felts=len(j['bytecode']),
                             casm_sha256=gb.sha256_bytes(json.dumps(j['bytecode']).encode()))
    return out


def capture(args, record):
    require_env()
    t, info = gb.tools()
    env = gb.tool_env(t)
    extra = ['--features', 'record'] if record else []
    cmd = gb.snforge_cmd(t, args.threads, extra)
    log = Path(args.out).with_suffix('.log')
    code, wall, peak = run_watched(cmd, env, log, args.max_rss_gb * 2**30)
    text = log.read_text()
    results, traces, summary, problems = gb.parse_output(text)
    if code != 0 or problems:
        sys.exit(f'snforge exit {code}, problems {problems[:5]}; see {log}')
    expected_n = len(CASES) + 1 + 6 * len(PROBE_SIZES)
    if summary is None or summary['passed'] != expected_n or summary['failed']:
        sys.exit(f'unexpected summary {summary}; see {log}')
    rows = {}
    for name, roots in traces.items():
        short = name[len(PREFIX):]
        for r in roots:
            gb.check_tree(r, problems, name)
        hits = [r for r in roots if r['contract'] in ('BeastPureComposer', 'KernelProbe')
                and r['selector'] in ('compose', 'compose_drift', 'build', 'noop', 'take',
                                      'smf_local', 'smf_kernel', 'build_felts', 'take_felts')]
        if len(hits) != 1:
            sys.exit(f'{name}: expected one measured call, got {len(hits)}')
        rows[short] = dict(gas=hits[0]['gas'], nested=gb.flatten(hits[0]['calls']),
                           test_l2_gas=results[name]['test_l2_gas'])
    if problems:
        sys.exit(f'gas tree problems: {problems[:5]}')
    if record:
        rec = {int(m[1]): (int(m[2]), int(m[3]), int(m[4]), m[5]) for m in re.finditer(
            r'^KCASE case=(\d+) felts=(\d+) hash=(\d+) midi_len=(\d+) kernel=(.*)$', text, re.M)}
        if set(rec) != set(range(len(CASES))):
            sys.exit('missing KCASE lines')
        arms = '\n'.join(f'        {i} => ({n}, {h}),' for i, (n, h, _, _) in sorted(rec.items()))
        (HERE / 'src/expected.cairo').write_text(
            '//! GENERATED by run.py record at the baseline: (felt count, poseidon) of the full Serde\n'
            '//! output (TinySynthSound: MIDI and settings) of each case.\n'
            'pub fn expected(case: u32) -> (u32, felt252) {\n    match case {\n' + arms +
            '\n        _ => panic!("unknown case"),\n    }\n}\n')
        for i, (_, _, midi_len, kernel) in rec.items():
            rows[f'case_{i:02}_{CASES[i][0]}']['midi_len'] = midi_len
        print('kernel class hash:', next(iter(rec.values()))[3])
    snap = dict(record=record, tools=info, git=gb.git_info(), command=cmd, wall_s=wall,
                peak_rss_mb=peak, summary=summary, classes=classes(), rows=rows)
    Path(args.out).write_text(json.dumps(snap, indent=2) + '\n')
    print(f'{summary}; wall {wall}s; peak RSS {peak} MB; classes {snap["classes"]}')


def require_env():
    if not os.environ.get('SCARB_TARGET_DIR'):
        sys.exit('set SCARB_TARGET_DIR (internal disk)')


def compare(args):
    a, b = (json.loads(Path(p).read_text()) for p in (args.base, args.cand))
    print(f'{"case":28s} {"base":>13s} {"cand":>13s} {"delta":>11s} {"%":>7s}  kernel call')
    for name in sorted(a['rows']):
        x, y = a['rows'][name]['gas'], b['rows'][name]['gas']
        k = [n['gas'] for n in b['rows'][name]['nested'] if n['selector'] == 'smf_byte_array']
        print(f'{name:28s} {x:13,d} {y:13,d} {y - x:11,d} {100 * (y / x - 1):7.3f}  {k}')
    for c in sorted(set(a['classes']) | set(b['classes'])):
        print(c, a['classes'].get(c), '->', b['classes'].get(c))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest='cmd', required=True)
    for name in ['record', 'run']:
        s = sub.add_parser(name)
        s.add_argument('--out', required=True)
        s.add_argument('--threads', type=int, default=2)
        s.add_argument('--max-rss-gb', type=float, default=10)
    s = sub.add_parser('compare')
    s.add_argument('base')
    s.add_argument('cand')
    args = p.parse_args()
    if args.cmd == 'compare':
        compare(args)
    else:
        capture(args, args.cmd == 'record')


if __name__ == '__main__':
    main()
