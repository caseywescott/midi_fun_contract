// Build the onchain TinySynth page: check and minify the pinned TinySynth, bundle the player,
// encode the stored segment, generate the Cairo data module.
//   node onchain/build.mjs   (needs: npx esbuild)
//
// Writes onchain/dist/{tinysynth.min.js,player.js,stored.b64} and core/midi_contracts/src/page/page_data.cairo.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { pageHtml, storedSegment } from './page.js';
import { PATCHES, UPSTREAM, patchTinySynth } from './vendor/webaudio-tinysynth/patch.mjs';
import { TINYCHIP_ONCHAIN } from './tinychip/config.mjs';
import { tinychipSource } from './tinychip/essentials.mjs';
import { BEATSYNC_ONCHAIN } from './beatsync/config.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));
const ESBUILD = ['-y', 'esbuild@0.23.0'];
mkdirSync(here + 'dist', { recursive: true });

// TinySynth stays a classic script (it attaches itself to `window`), so it is minified, not bundled.
const tinysynth = patchTinySynth(readFileSync(here + 'vendor/webaudio-tinysynth/webaudio-tinysynth.js', 'utf8'));
const banner = `/*! webaudio-tinysynth (c) g200kg, Apache-2.0; Provable Games fork ${UPSTREAM.commit.slice(0, 7)}, modified (see NOTICE)${PATCHES.length ? ' + ' + PATCHES.map((p) => p.name).join(', ') : ''} */`;
const tinysynthMin = banner + execFileSync('npx', [...ESBUILD, '--loader=js', '--minify', '--charset=utf8', '--target=es2020', '--legal-comments=none'], { input: tinysynth }).toString().trim();
writeFileSync(here + 'dist/tinysynth.min.js', tinysynthMin + '\n');

execFileSync('npx', [...ESBUILD, here + 'player-src.js', '--bundle', '--minify', '--format=iife', '--charset=utf8', '--target=es2020', `--outfile=${here}dist/player.js`], { stdio: 'inherit' });
const player = readFileSync(here + 'dist/player.js', 'utf8').trim();

// Optional TinyChip (onchain/tinychip): the 20-preset runtime with its orchestration, stored onchain
// when enabled and always built for clients, plus the full 100-preset bank as a client add-on.
const minify = (input) => execFileSync('npx', [...ESBUILD, '--loader=js', '--minify', '--charset=utf8', '--target=es2020'], { input }).toString().trim();
const tinychip = minify(tinychipSource());
writeFileSync(here + 'dist/tinychip.min.js', tinychip + '\n');
writeFileSync(here + 'dist/tinychip-bank.min.js', minify(readFileSync(here + 'tinychip/tinysynth-chip.js', 'utf8')) + '\n');

// Optional BeatSync (onchain/beatsync): built for clients, stored onchain when enabled. It loads before
// the player so the player's DOMContentLoaded hook finds it.
const beatsync = execFileSync('npx', [...ESBUILD, '--loader=js', '--minify', '--charset=utf8', '--target=es2020'], { input: readFileSync(here + 'beatsync/beatsync.js', 'utf8') }).toString().trim();
writeFileSync(here + 'dist/beatsync.min.js', beatsync + '\n');

const js = [tinysynthMin, ...(TINYCHIP_ONCHAIN ? [tinychip] : []), ...(BEATSYNC_ONCHAIN ? [beatsync] : []), player].join('\n');
const stored = storedSegment(js);
writeFileSync(here + 'dist/stored.b64', stored);
const sha = createHash('sha256').update(stored).digest('hex');

// The stored segment is emitted as a ByteArray string literal: the compiler builds it from one
// constant per 31-byte word, which costs ~200 gas a word, ~20x less than deserializing the words
// from a felt array. It is base64 text, so it needs no escaping.
if (!/^[A-Za-z0-9+/]*$/.test(stored)) throw new Error('stored segment is not plain base64 text');
const words = Math.floor(stored.length / 31);

// A comment paragraph wrapped as scarb fmt wraps it (greedy, 100 columns), so the file stays fmt-clean.
const wrapComment = (text, width = 100) => {
  const lines = [];
  let line = '//';
  for (const w of text.split(/\s+/).filter(Boolean)) {
    if (line !== '//' && line.length + 1 + w.length > width) { lines.push(line); line = '//'; }
    line += ' ' + w;
  }
  return [...lines, line].join('\n');
};
const cairo = `// Generated by onchain/build.mjs. Do not edit.
//
${wrapComment(`base64('"animation_url":"data:text/html;base64,' ++ base64(page)), where page is the HTML head, the webaudio-tinysynth (Provable Games fork ${UPSTREAM.commit.slice(0, 7)}, Apache-2.0: ${tinysynthMin.length} bytes minified) and the player (${player.length} bytes), then the opening of the MIDI block: ${pageHtml(js).length} bytes of HTML,`)}
${wrapComment(`${stored.length} characters, ${words} words of 31 bytes and ${stored.length - words * 31} pending bytes, as a string literal. sha256(stored) = ${sha}.`)}

pub const STORED_LEN: usize = ${stored.length};

/// The stored segment as a ByteArray, built from one constant per word (cheaper than
/// deserializing the words from a felt array or appending them one by one).
pub fn stored_segment() -> ByteArray {
    "${stored}"
}
`;
writeFileSync(here + '../../../core/midi_contracts/src/page/page_data.cairo', cairo);
console.log(`tinysynth ${tinysynthMin.length} B · player ${player.length} B · page ${pageHtml(js).length} B · stored ${stored.length} chars · ${words} words · sha256 ${sha.slice(0, 16)}…`);
