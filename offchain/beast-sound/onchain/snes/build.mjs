import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { readWav, prepare } from './prepare.mjs';
import { encodeBRR, decodeBRR } from './brr.js';
import { envelope, integer, validateBank } from './bank.js';
import { storedSegment } from '../page.js';

const here = dirname(fileURLToPath(import.meta.url));
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
export const safeJson = (data) => JSON.stringify(data).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

export function buildBank(manifestPath) {
  const path = manifestPath instanceof URL ? fileURLToPath(manifestPath) : resolve(manifestPath);
  const manifest = JSON.parse(readFileSync(path, 'utf8'));
  if (manifest.format !== 'BSBRR1' || !Array.isArray(manifest.instruments) || manifest.instruments.length > 256) throw new Error('Expected BSBRR1 manifest with up to 256 instruments');
  const budget = manifest.maxBrrBytes ?? 20480;
  if (!integer(budget, 9, 65536)) throw new Error('maxBrrBytes must be 9–65536');
  const bank = { format: 'BSBRR1', name: manifest.name ?? '', samples: [], instruments: [] };
  const samples = new Map(), report = [];
  let total = 0;
  for (const inst of manifest.instruments) {
    if (typeof inst.file !== 'string' || !inst.file || !inst.credit || ['author', 'license', 'source'].some((k) => typeof inst.credit[k] !== 'string' || !inst.credit[k].trim())) throw new Error(`Supply file and credit author/license/source for ${inst.id}`);
    const wav = readWav(readFileSync(resolve(dirname(path), inst.file)));
    const { pcm, rate, loopStart } = prepare(wav, inst);
    const bytes = encodeBRR(pcm, loopStart), key = `${rate}:${loopStart}:${sha(bytes)}`;
    if (!samples.has(key)) {
      total += bytes.length;
      if (total > budget) throw new Error(`BRR budget exceeded: ${total} > ${budget} bytes`);
      samples.set(key, bank.samples.length);
      bank.samples.push({ rate, loopStart, data: Buffer.from(bytes).toString('base64') });
    }
    bank.instruments.push({ id: inst.id, ...(inst.drum === undefined ? { program: inst.program } : { drum: inst.drum }), sample: samples.get(key), rootNote: inst.rootNote, tuneCents: inst.tuneCents ?? 0, volume: inst.volume ?? 0.5, envelope: envelope(inst.envelope), credit: inst.credit });
    const decoded = decodeBRR(bytes, loopStart);
    let error = 0, signal = 0;
    for (let i = 0; i < pcm.length; i++) { error += (pcm[i] - decoded[i]) ** 2; signal += pcm[i] ** 2; }
    report.push({ id: inst.id, frames: pcm.length, rate, loopStart, brrBytes: bytes.length, snrDb: error && signal ? +(10 * Math.log10(signal / error)).toFixed(2) : null,
      loopJump: loopStart === null ? null : Math.abs(decoded[decoded.length - 1] - decoded[loopStart]) / 32768 });
  }
  validateBank(bank);
  return { bank, report: { format: 'BSBRR1', brrBytes: total, decodedPcm16Bytes: total / 9 * 32, budgetBytes: budget, uniqueSamples: bank.samples.length, sharedSampleReferences: bank.instruments.length - bank.samples.length, instruments: report, bankJsonBytes: Buffer.byteLength(safeJson(bank)) } };
}

export async function bundleBank(bank) {
  validateBank(bank);
  // Store a common credit once in the page; bank.json keeps each instrument self-contained.
  const credit = bank.instruments[0]?.credit;
  const shared = bank.instruments.length > 1 && credit && bank.instruments.every((i) => safeJson(i.credit) === safeJson(credit));
  const data = shared ? { ...bank, instruments: bank.instruments.map(({ credit: _, ...i }) => i) } : bank;
  const source = `const bank=${safeJson(data)};` + (shared ? `const credit=${safeJson(credit)};for(const i of bank.instruments)i.credit=credit;` : '');
  const result = await build({ stdin: { contents: `import {attach,createSampler} from './runtime.js'; ${source} window.SnesBank={bank,attach:(s,o)=>attach(s,bank,o),createSampler:(a,o)=>createSampler(a,bank,o)};`, resolveDir: here, loader: 'js' }, bundle: true, minify: true, format: 'iife', target: 'es2020', write: false });
  return result.outputFiles[0].text.trim();
}

export function cairoData(stored) {
  if (!/^[A-Za-z0-9+/]+$/.test(stored) || stored.length % 31) throw new Error('Expected aligned, unpadded base64');
  return `// Generated by onchain/snes/build.mjs. Do not edit.\n// sha256 ${sha(stored)}\n// Pre-encoded page: ${stored.length} bytes / ${stored.length / 31} data words.\n// Data words are not a CASM size estimate. Compile before deployment.\n\npub const STORED_LEN: usize = ${stored.length};\n\npub fn stored_segment() -> ByteArray {\n    "${stored}"\n}\n`;
}

export async function buildArtifacts(manifestPath, outDir) {
  const { bank, report } = buildBank(manifestPath), script = await bundleBank(bank);
  const player = await build({ entryPoints: [resolve(here, 'player-src.js')], bundle: true, minify: true, format: 'iife', target: 'es2020', write: false });
  // Reuse the existing pinned/minified TinySynth artifact, verified by the normal page build.
  const tiny = readFileSync(resolve(here, '../dist/tinysynth.min.js'), 'utf8').trim();
  const pageScript = [tiny, script, player.outputFiles[0].text.trim()].join('\n');
  const stored = storedSegment(pageScript);
  const baseline = readFileSync(resolve(here, '../dist/stored.b64'), 'utf8');
  Object.assign(report, { runtimeAndBankBytes: Buffer.byteLength(script), pageStoredBytes: stored.length, pageDataWords: stored.length / 31, deltaStoredBytesVsCurrentPage: stored.length - baseline.length,
    note: 'Includes bank JSON/base64 and outer page base64. Not compiled CASM size or gas. No samples are bundled unless supplied in the manifest.' });
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, 'bank.json'), safeJson(bank) + '\n');
  writeFileSync(resolve(outDir, 'bank.min.js'), script + '\n');
  writeFileSync(resolve(outDir, 'stored.b64'), stored);
  writeFileSync(resolve(outDir, 'page_data.cairo'), cairoData(stored));
  writeFileSync(resolve(outDir, 'report.json'), JSON.stringify(report, null, 2) + '\n');
  const demo = await build({ stdin: { contents: "import {demoSequence,scheduleDemo} from './demo.js';window.SnesDemo={sequence:demoSequence,schedule:scheduleDemo};", resolveDir: here }, bundle: true, minify: true, write: false });
  const lab = readFileSync(resolve(here, 'lab.html'), 'utf8').replace('/*__SYNTH__*/', () => tiny).replace('/*__BANK__*/', () => script).replace('/*__DEMO__*/', () => demo.outputFiles[0].text);
  writeFileSync(resolve(outDir, 'lab.html'), lab);
  return report;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const report = await buildArtifacts(process.argv[2] ?? resolve(here, 'manifest.json'), resolve(process.argv[3] ?? resolve(here, 'dist')));
    console.log(JSON.stringify(report, null, 2));
  } catch (error) { console.error(`SNES bank: ${error.message}`); process.exitCode = 1; }
}
