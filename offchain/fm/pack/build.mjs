// Build the Loot FM pack from the reference Kankyo bank script:
//   node pack/build.mjs [bank script, default kankyo.min.js]
// 1. reads the bank's instruments and definitions (by running it in Node; nothing depends on its minified names),
// 2. writes pack/kankyo-data.js: the definitions in compact form (see data.js), checking that they decode to
//    exactly the reference's,
// 3. bundles pack/main.js and wraps it in `function LootFmPack(){...}` (its own source is the workers' script),
// 4. writes dist/loot-fm-pack.min.js, dist/loot-fm-pack.min.js.gz, dist/loot-fm-pack.min.js.gz.b64 and dist/demo.html.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { gzipSync, constants } from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve, dirname } from 'node:path';
import { build } from 'esbuild';
import { loadReference } from './ref.mjs';
import { GEN, stringZone } from './gen.js';

const here = dirname(fileURLToPath(import.meta.url)), root = resolve(here, '..'), dist = resolve(root, 'dist');
const ref = loadReference(resolve(root, process.argv[2] ?? 'kankyo.min.js'));
const J = (v) => JSON.stringify(v), clone = (v) => JSON.parse(J(v));

// ---- the reference's instruments, as rows
const rows = [], drums = [];
for (const inst of ref.bank.instruments) {
  const d = ref.jobs[inst.sample].a[0];
  if (inst.drum !== undefined) { drums.push([inst.id, inst.drum, inst.volume, d]); continue; }
  const id = inst.id.replace(/-\d+$/, ''), e = inst.envelope, last = rows[rows.length - 1];
  if (last && last[0] === id) { last[3] = inst.rootNote; continue; }
  rows.push([id, inst.program, inst.rootNote, inst.rootNote, inst.volume, [e.attack, e.decay, e.sustain, e.release], d]);
}

// ---- compact definitions
function compact(d, lo, hi) {
  const e = clone(d); delete e.base; delete e.trim; if (e.t === 'f') delete e.t; // trim was folded into lvl; base is redone below
  if (e.zones) {
    const roots = e.zones.map((_, k) => lo + 4 * k);
    const gen = Object.keys(GEN).find((g) => e.zones.every((z, k) => J(GEN[g](roots[k])) === J(z)));
    if (gen) { e.Z = gen; delete e.zones; }
    else {
      const T = (v) => Math.round(v * 1000), S = e.zones.map((z) => { const o = z.ops, h = o.length / 2, a = [T(o[1]?.[7] ?? 0), T(o[0][5])]; for (let j = 1; j < h; j++) { const op = o[j]; if (+(0.28 * op[3]).toFixed(3) === op[2]) a.push(op[0], T(op[5]), T(op[3])); else a.push(-op[0], T(op[5]), T(op[3]), T(op[2])); } return J(stringZone(a)) === J(z) ? a : null; });
      if (S.every(Boolean)) { e.S = S; delete e.zones; }
    }
  }
  return e;
}
// each def may be stored as another's (earlier in the list) with the keys that differ, whichever is shorter
function withBases(list, at) {
  const full = [];
  return list.map((row) => {
    const e = compact(row[at], row[2], row[3]); let best = e;
    full.forEach((b, i) => { const o = { b: i }; for (const k of new Set([...Object.keys(e), ...Object.keys(b)])) if (J(e[k]) !== J(b[k])) o[k] = e[k] ?? null; if (J(o).length + 2 < J(best).length) best = o; });
    full.push(e); return [...row.slice(0, at), best];
  });
}
const ROWS = withBases(rows, 6), DRUMS = withBases(drums, 3);
writeFileSync(resolve(here, 'kankyo-data.js'), `// Generated by build.mjs from the reference Kankyo bank (kankyo.min.js); see data.js for the format.\nexport const ROWS = ${J(ROWS)};\nexport const DRUMS = ${J(DRUMS)};\n`);

// the decoded definitions must be the reference's (keys the engine reads: all but base and trim)
const { decode } = await import(pathToFileURL(resolve(here, 'data.js')).href + '?' + Date.now());
const dec = decode(), strip = (d) => { const o = clone(d); delete o.base; delete o.trim; return J(Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)))); };
rows.forEach((r, i) => { const x = dec.inst[i]; if (strip(r[6]) !== strip(x.d) || J(r.slice(0, 6)) !== J([x.id, x.program, x.lo, x.hi, x.volume, x.env])) throw new Error('decoded definition differs: ' + r[0]); });
drums.forEach((r, i) => { const x = dec.drums[i]; if (strip(r[3]) !== strip(x.d) || J(r.slice(0, 3)) !== J([x.id, x.key, x.volume])) throw new Error('decoded drum differs: ' + r[0]); });

// ---- bundle
const inner = (await build({ entryPoints: [resolve(here, 'main.js')], bundle: true, minify: true, format: 'iife', target: 'es2020', write: false, legalComments: 'none' })).outputFiles[0].text.trim();
const text = `!function LootFmPack(){${inner}}();\n`;
mkdirSync(dist, { recursive: true });
const gz = gzipSync(Buffer.from(text), { level: constants.Z_BEST_COMPRESSION });
writeFileSync(resolve(dist, 'loot-fm-pack.min.js'), text);
writeFileSync(resolve(dist, 'loot-fm-pack.min.js.gz'), gz);
writeFileSync(resolve(dist, 'loot-fm-pack.min.js.gz.b64'), gz.toString('base64')); // no newline: the contract returns exactly this
// the demo page, carrying the pack as the contract stores it
writeFileSync(resolve(dist, 'demo.html'), readFileSync(resolve(here, 'demo.src.html'), 'utf8').replace('/*__PACK_B64__*/', () => gz.toString('base64')));
const dataText = (await build({ stdin: { contents: readFileSync(resolve(here, 'kankyo-data.js'), 'utf8'), loader: 'js' }, minify: true, write: false })).outputFiles[0].text;
const refGz = gzipSync(Buffer.from(ref.text), { level: 9 }).length;
console.log(JSON.stringify({ pack: { raw: text.length, gzip: gz.length, gzipBase64: Math.ceil(gz.length / 3) * 4, data: dataText.length }, reference: { raw: Buffer.byteLength(ref.text.replace('jobs:f0,', '')), gzip: refGz }, instruments: rows.length, drums: drums.length, zones: ref.jobs.length }, null, 1));
