// Write the Cairo data module for the LootFmPack contract from the built pack:
//   node pack/cairo.mjs
// loot/loot_contracts/src/fm_pack_data.cairo: dist/loot-fm-pack.min.js.gz.b64 (the gzip bytes as base64: Cairo
// string literals take ASCII only) as ByteArray string literals, one per chunk of 3968 characters (128 words of
// 31 bytes, so chunks join word for word, and a multiple of 4, so each chunk is base64 on its own); plus the
// lengths and sha256s.
// loot/loot_contracts/data/loot_fm_pack_b64.txt: the same text as a serialized ByteArray (one felt a line), which
// the contract's test reads (snforge read_txt) to check that the class returns exactly the dist file.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = fileURLToPath(new URL('.', import.meta.url)), root = resolve(here, '..'), pkg = resolve(root, '../../loot/loot_contracts');
const gzBytes = readFileSync(resolve(root, 'dist/loot-fm-pack.min.js.gz')), gz = readFileSync(resolve(root, 'dist/loot-fm-pack.min.js.gz.b64')), js = readFileSync(resolve(root, 'dist/loot-fm-pack.min.js'));
const CHUNK = 31 * 128, sha = (b) => createHash('sha256').update(b).digest('hex');
const lit = (b) => b.toString('latin1');
if (!/^[A-Za-z0-9+/]+=*$/.test(gz.toString()) || Buffer.compare(Buffer.from(gz.toString(), 'base64'), gzBytes)) throw new Error('dist .gz.b64 is not the .gz as base64');
const chunks = []; for (let i = 0; i < gz.length; i += CHUNK) chunks.push(gz.subarray(i, i + CHUNK));
const VERSION = 1;
const src = `// Generated by offchain/fm/pack/cairo.mjs from offchain/fm/dist/loot-fm-pack.min.js.gz.b64. Do not edit.
//
// The Loot FM pack (the Kankyo FM instruments, engine and sampler as one script, ${js.length} bytes,
// sha256 ${sha(js)}), gzip-compressed (${gzBytes.length} bytes, sha256 ${sha(gzBytes)}) and as base64:
// ${gz.length} characters, sha256 ${sha(gz)}, in ${chunks.length} chunks of up to ${CHUNK} (${CHUNK / 31} words of 31 bytes).

pub const VERSION: u32 = ${VERSION};
pub const PACK_LEN: u32 = ${gz.length};
pub const GZIP_LEN: u32 = ${gzBytes.length};
pub const SCRIPT_LEN: u32 = ${js.length};
pub const CHUNK_LEN: u32 = ${CHUNK};
pub const CHUNK_COUNT: u32 = ${chunks.length};
/// sha256 of the stored text (the base64), as a u256
pub const PACK_SHA256: u256 = 0x${sha(gz)};

/// Chunk \`index\` of the base64 text (empty past the last).
pub fn chunk(index: u32) -> ByteArray {
    match index {
${chunks.map((c, i) => `        ${i} => "${lit(c)}",`).join('\n')}
        _ => "",
    }
}
`;
writeFileSync(resolve(pkg, 'src/fm_pack_data.cairo'), src);
// the test fixture: ByteArray serde [full words, word..., pending word, pending length]
const words = []; let i = 0; for (; i + 31 <= gz.length; i += 31) words.push(BigInt('0x' + gz.subarray(i, i + 31).toString('hex')));
const rest = gz.subarray(i), pending = rest.length ? BigInt('0x' + rest.toString('hex')) : 0n;
mkdirSync(resolve(pkg, 'data'), { recursive: true });
writeFileSync(resolve(pkg, 'data/loot_fm_pack_b64.txt'), [words.length, ...words, pending, rest.length].map(String).join('\n') + '\n');
console.log(JSON.stringify({ gzipBytes: gzBytes.length, base64Chars: gz.length, scriptBytes: js.length, chunks: chunks.length, words: Math.ceil(gz.length / 31), cairoSourceBytes: src.length, sha256Gzip: sha(gz) }));
