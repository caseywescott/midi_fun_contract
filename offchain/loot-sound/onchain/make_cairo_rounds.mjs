// Writes loot/loot_composer/src/rounds_data.cairo from src/loot_rounds.js: the chord loops (packed, with
// the mask of the degrees they use, so a mode's loops are filtered on chain), the modes, the deals, and
// each meter's cells, cell families, motif heads, bass figures and percussion bars (packed, flat, with
// start indices).   node onchain/make_cairo_rounds.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as M from '../src/loot_rounds.js';

const out = fileURLToPath(new URL('../../../loot/loot_composer/src/rounds_data.cairo', import.meta.url));
const arr = (name, ty, xs, doc) => `/// ${doc}\npub const ${name}: [${ty}; ${xs.length}] = [${xs.join(', ')}];\n`;
// u32 values 7 to a felt252, item i at bit 32 * (i % 7) of felt i / 7 (read with common::at32)
const packed = (name, xs, doc) => {
  const fs = [];
  for (let i = 0; i < xs.length; i += 7) {
    let v = 0n;
    xs.slice(i, i + 7).forEach((x, j) => { if (!(x >= 0 && x < 2 ** 32)) throw new Error(name + ' u32'); v += BigInt(x) << BigInt(32 * j); });
    fs.push('0x' + v.toString(16));
  }
  return `/// ${doc} (u32s 7 to a felt: common::at32)\npub const ${name}: [felt252; ${fs.length}] = [${fs.join(', ')}];\n`;
};
const okMask = (m) => { let k = 0; for (let r = 1; r < 7; r++) if ('Mm'.includes(M.quality(M.MODE_SCALES[m], r))) k |= 1 << r; return k; };
const pack = (l) => { let v = 0, mask = 0; l.forEach((r, i) => { v += r * 8 ** i; if (r) mask |= 1 << r; }); return v + mask * 8 ** l.length; };
// check the on-chain filter reproduces loopsFor
for (const m of M.ROUND_MODES) for (const eight of [false, true]) {
  const bad = 0x7e & ~okMask(m), mine = (eight ? M.LOOPS8 : M.LOOPS4).filter((l) => (Math.floor(pack(l) / 8 ** l.length) & bad) === 0);
  if (JSON.stringify(mine) !== JSON.stringify(M.loopsFor(m, eight))) throw new Error('loop filter ' + m);
}
const SRC = { A: 0, P: 1, U: 2, L: 3, S: 4, R: 5 }, BSRC = { R: 0, O: 1, T: 2, F: 3, N: 4 };
const flat = (groups, enc) => { const items = [], at = []; for (const g of groups) { at.push(items.length); for (const x of g) items.push(enc(x)); } at.push(items.length); return [items, at]; };
const [cells, cellAt] = flat(M.METERS.flatMap((m) => m.cells), ([o, l, s]) => o * 65536 + l * 8 + SRC[s]);
const [bass, bassAt] = flat(M.METERS.flatMap((m) => [...m.bass2, ...m.bass1]), ([o, l, s]) => o * 65536 + l * 8 + BSRC[s]);
const [perc, percAt] = flat(M.METERS.flatMap((m) => m.perc), ([o, k, v]) => o * 65536 + k * 256 + v);
for (const m of M.METERS) if (m.cells.length !== 12 || m.bass2.length !== 6 || m.bass1.length !== 6 || m.perc.length !== 3) throw new Error('meter shape');
const family = M.METERS.flatMap((m) => m.family.flatMap((t) => t.map((f) => f.reduce((v, c, i) => v + c * 16 ** i, 0))));
const heads = M.METERS.flatMap((m) => m.head.map(([a, b]) => a * 65536 + b));
const code = (a) => a.reduce((v, r, i) => v + r * 3 ** i, 0);
const modes = M.ROUND_MODES;
const src = `//! The Rounds' tables (offchain/loot-sound/src/loot_rounds.js), packed.
//! Generated by offchain/loot-sound/onchain/make_cairo_rounds.mjs: do not edit.

${packed('LOOPS4', M.LOOPS4.map(pack), 'The four-chord loops: roots base 8 (root i at 8^i), then the mask of the roots used (bit r) at 8^4.')}
${packed('LOOPS8', M.LOOPS8.map(pack), 'The eight-chord loops: roots base 8, the mask at 8^8.')}
${arr('MODE_IDS', 'u8', modes, 'ROUND_MODES.')}
${arr('MODE_SCALE', 'u32', modes.map((m) => M.MODE_SCALES[m].reduce((v, x, i) => v + x * 16 ** i, 0)), "Each mode's scale, base 16.")}
${arr('MODE_BAD', 'u32', modes.map((m) => 0x7e & ~okMask(m)), 'The degrees (bit r) whose triad is neither major nor minor.')}
${arr('MODE_CAD', 'u32', modes.map((m) => M.cadenceRoot(m)), 'cadenceRoot.')}
${arr('MODE_DIM', 'bool', modes.map((m) => M.quality(M.MODE_SCALES[m], 0) === 'd'), 'A diminished tonic.')}
${arr('MODE_N4', 'u32', modes.map((m) => M.loopsFor(m).length), 'loopsFor(mode).length.')}
${arr('MODE_N8', 'u32', modes.map((m) => M.loopsFor(m, true).length), 'loopsFor(mode, true).length.')}
${arr('ASSIGN3', 'u32', M.ASSIGN[3].map(code), 'ASSIGN[3], each deal base 3 (line j at 3^j).')}
${arr('ASSIGN4', 'u32', M.ASSIGN[4].map(code), 'ASSIGN[4].')}
${arr('SHAPES', 'u32', [3, 4].flatMap((K) => M.SHAPES[K].map((s) => s.reduce((v, x, i) => v + x * 8 ** i, 0))), 'SHAPES[3] then SHAPES[4], base 8.')}
${arr('CONTOURS', 'u32', [3, 4].flatMap((K) => M.CONTOURS[K].map((s) => s.reduce((v, x, i) => v + x * 8 ** i, 0))), 'CONTOURS[3] then CONTOURS[4], base 8.')}
${arr('EPISODES', 'u32', M.EPISODES.map((e) => e.step + 8 * (e.cycle[0] + 3 * e.cycle[1] + 9 * e.cycle[2]) + (e.motif ? 1024 : 0)), 'Each episode: step, then 8 * its cycle base 3, 1024 for the motif.')}
${packed('CELL_NOTES', cells, "The meters' cells, flat: offset * 65536 + length * 8 + source (A P U L S R).")}
${packed('CELL_AT', cellAt, 'Where cell meter * 12 + c starts in CELL_NOTES (and ends: the next).')}
${packed('FAMILY', family, 'meter.family[type][activity], at meter * 9 + type * 3 + activity: four cells base 16.')}
${packed('HEADS', heads, 'meter.head, at meter * 3 + h: the lengths, first * 65536 + second.')}
${packed('BASS_NOTES', bass, 'The bass figures, flat: offset * 65536 + length * 8 + source (R O T F N).')}
${packed('BASS_AT', bassAt, 'Where figure (meter * 2 + (0 bass2, 1 bass1)) * 6 + f starts in BASS_NOTES.')}
${packed('PERC_HITS', perc, 'The percussion bars, flat: offset * 65536 + key * 256 + velocity.')}
${packed('PERC_AT', percAt, 'Where bar meter * 3 + i starts in PERC_HITS.')}`;
writeFileSync(out, src);
console.log('wrote', out);
