// Writes loot/loot_composer/src/species.cairo from src/loot_species.js (the 30 Loot Beasts' Species
// Song key, mode and the first six theme degrees).   node onchain/make_cairo_species.mjs
import { writeFileSync } from 'node:fs';
import { SPECIES } from '../src/loot_species.js';
import { LOOT_FIRST, musicalId } from '../src/loot_beasts.js';
// one u64 per species: tier, type, tonic, mode (two nibbles, low first), then the six degrees + 8, 4 bits each from
// the low end
const rows = SPECIES.map((s, i) => {
  if (s.id !== SPECIES[0].id + i) throw new Error('ids not consecutive');
  const f = [s.tier, s.type, s.tonicPc, s.mode % 16, s.mode >> 4, ...s.degrees.map((d) => d + 8)];
  if (s.mode >= 256 || f.length !== 11 || f.some((x) => !(x >= 0 && x < 16))) throw new Error('species field out of range ' + s.id);
  return '0x' + f.reduce((v, x, k) => v + (BigInt(x) << BigInt(4 * k)), 0n).toString(16);
}).join(', ');
const out = `//! The 30 Loot Dungeon Beasts (public ids ${SPECIES[0].id}-${SPECIES[SPECIES.length - 1].id}): tier, family, Species Song
//! tonic pitch class and mode, and the theme's first six scale degrees; and each Beast's musical id
//! (loothero's PR #35): the soundtrack written at the provisional ids ${musicalId(SPECIES[0].id)}-${musicalId(SPECIES[SPECIES.length - 1].id)}.
//! Generated by offchain/loot-sound/onchain/make_cairo_species.mjs from src/loot_species.js: do not edit.

pub const LOOT_FIRST: u32 = ${SPECIES[0].id};
pub const LOOT_COUNT: u32 = ${SPECIES.length};
/// The musical id of LOOT_FIRST: a Beast's music (its random streams, leads, drift and band) is keyed by
/// its musical id, the public id less ${LOOT_FIRST - musicalId(LOOT_FIRST)}.
pub const MUSICAL_FIRST: u32 = ${musicalId(LOOT_FIRST)};

/// Loot Beast \`id\`'s musical id (src/loot_beasts.js \`musicalId\`): the soundtrack written at the
/// provisional ids; never a registry species id (those stay LOOT_FIRST..LOOT_FIRST + LOOT_COUNT).
/// No range check here (CASM size: no panic path at each call): every track checks \`id\` with
/// \`loot_species\` ('not a Loot Beast'), so an id out of range reverts all the same.
#[inline(always)]
pub fn musical_id(id: u32) -> u32 {
    let (x, _) = core::num::traits::OverflowingSub::overflowing_sub(id, ${LOOT_FIRST - musicalId(LOOT_FIRST)});
    x
}

#[derive(Copy, Drop, Serde, PartialEq, Debug)]
pub struct LootSpecies {
    /// The public id.
    pub id: u32,
    /// The musical id (\`musical_id(id)\`): what the engines key a Beast's music by.
    pub music: u32,
    /// 1-5.
    pub tier: u8,
    /// 0 magic, 1 hunter, 2 brute.
    pub beast_type: u8,
    pub tonic_pc: u8,
    /// The Beasts engine's mode id (${[...new Set(SPECIES.map((s) => s.mode))].sort((a, b) => a - b).join(', ')} here).
    pub mode: u8,
    /// Scale degrees, -7..7.
    pub degrees: [i8; 6],
}

/// Loot Beast \`id\` (LOOT_FIRST..LOOT_FIRST + LOOT_COUNT).
pub fn loot_species(id: u32) -> LootSpecies {
    assert(id >= LOOT_FIRST && id < LOOT_FIRST + LOOT_COUNT, 'not a Loot Beast');
    let i = id - LOOT_FIRST;
    let mut x: u64 = *ALL.span().at(i);
    let tier = nib(ref x);
    let beast_type = nib(ref x);
    let tonic_pc = nib(ref x);
    let mode = nib(ref x) + 16 * nib(ref x);
    let degrees = [deg(ref x), deg(ref x), deg(ref x), deg(ref x), deg(ref x), deg(ref x)];
    LootSpecies { id, music: i + MUSICAL_FIRST, tier, beast_type, tonic_pc, mode, degrees }
}

/// The low 4 bits of \`x\`, shifted out.
#[inline(never)]
fn nib(ref x: u64) -> u8 {
    let (q, r) = DivRem::div_rem(x, 16);
    x = q;
    match r.try_into() {
        Option::Some(v) => v,
        Option::None => 0,
    }
}

/// A degree (stored + 8).
#[inline(never)]
fn deg(ref x: u64) -> i8 {
    let d: felt252 = nib(ref x).into() - 8;
    match d.try_into() {
        Option::Some(v) => v,
        Option::None => 0,
    }
}

/// Each species: tier, type, tonic, mode (two nibbles), then the six degrees + 8, 4 bits each from the low end.
const ALL: [u64; ${SPECIES.length}] = [${rows}];
`;
writeFileSync(new URL('../../../loot/loot_composer/src/species.cairo', import.meta.url), out);
console.log('wrote species.cairo,', SPECIES.length, 'species');
