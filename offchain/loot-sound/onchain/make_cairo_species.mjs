// Writes loot/loot_composer/src/species.cairo from src/loot_species.js (the 30 Loot Beasts' Species
// Song key, mode and the first six theme degrees).   node onchain/make_cairo_species.mjs
import { writeFileSync } from 'node:fs';
import { SPECIES } from '../src/loot_species.js';
// one u64 per species: tier, type, tonic, mode, then the six degrees + 8, 4 bits each from the low end
const rows = SPECIES.map((s, i) => {
  if (s.id !== SPECIES[0].id + i) throw new Error('ids not consecutive');
  const f = [s.tier, s.type, s.tonicPc, s.mode, ...s.degrees.map((d) => d + 8)];
  if (f.length !== 10 || f.some((x) => !(x >= 0 && x < 16))) throw new Error('species field out of range ' + s.id);
  return '0x' + f.reduce((v, x, k) => v + (BigInt(x) << BigInt(4 * k)), 0n).toString(16);
}).join(', ');
const out = `//! The 30 Loot Dungeon Beasts (PLACEHOLDER ids 76-105 until Provable Games sends the list): tier,
//! family, Species Song tonic pitch class and mode, and the theme's first six scale degrees.
//! Generated by offchain/loot-sound/onchain/make_cairo_species.mjs from src/loot_species.js: do not edit.

pub const LOOT_FIRST: u32 = ${SPECIES[0].id};
pub const LOOT_COUNT: u32 = ${SPECIES.length};

#[derive(Copy, Drop, Serde, PartialEq, Debug)]
pub struct LootSpecies {
    pub id: u32,
    /// 1-5.
    pub tier: u8,
    /// 0 magic, 1 hunter, 2 brute.
    pub beast_type: u8,
    pub tonic_pc: u8,
    /// The Beasts engine's mode id (4, 5, 7, 8 here).
    pub mode: u8,
    /// Scale degrees, -7..7.
    pub degrees: [i8; 6],
}

/// Loot Beast \`id\` (LOOT_FIRST..LOOT_FIRST + LOOT_COUNT).
pub fn loot_species(id: u32) -> LootSpecies {
    assert(id >= LOOT_FIRST && id < LOOT_FIRST + LOOT_COUNT, 'not a Loot Beast');
    let mut x: u64 = *ALL.span().at(id - LOOT_FIRST);
    let tier = nib(ref x);
    let beast_type = nib(ref x);
    let tonic_pc = nib(ref x);
    let mode = nib(ref x);
    let degrees = [deg(ref x), deg(ref x), deg(ref x), deg(ref x), deg(ref x), deg(ref x)];
    LootSpecies { id, tier, beast_type, tonic_pc, mode, degrees }
}

/// The low 4 bits of \`x\`, shifted out.
#[inline(never)]
fn nib(ref x: u64) -> u8 {
    let (q, r) = DivRem::div_rem(x, 16);
    x = q;
    r.try_into().unwrap()
}

/// A degree (stored + 8).
#[inline(never)]
fn deg(ref x: u64) -> i8 {
    let d: felt252 = nib(ref x).into() - 8;
    d.try_into().unwrap()
}

/// Each species: tier, type, tonic, mode, then the six degrees + 8, 4 bits each from the low end.
const ALL: [u64; ${SPECIES.length}] = [${rows}];
`;
writeFileSync(new URL('../../../loot/loot_composer/src/species.cairo', import.meta.url), out);
console.log('wrote species.cairo,', SPECIES.length, 'species');
