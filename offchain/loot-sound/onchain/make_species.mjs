// Writes src/loot_species.js: each Loot Dungeon Beast's Species Song key and theme (the editions
// play it), from the Beasts v1.0.1 composer's JS reference.
//   node onchain/make_species.mjs <midi_fun_contract checkout at v1.0.1>
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { LOOT_BEASTS } from '../src/loot_beasts.js';

const ref = process.argv[2];
if (!ref) { console.error('usage: node onchain/make_species.mjs <midi_fun_contract checkout>'); process.exit(2); }
const src = (f) => import(pathToFileURL(join(ref, 'offchain/beast-sound/src', f)).href);
const { engine: E } = await src('index.js');
const { createEngineV11 } = await src('engine_v11.js');
const LAB = await src('lab.js');
const V11E = createEngineV11(E);
const recs = LOOT_BEASTS.map((x) => {
  const b = { id: x.id, prefix: 0, suffix: 0, level: 1, health: 100, shiny: 0, animated: 0, tier: x.tier, beast_type: x.type };
  const o = LAB.sampleTrackMidi(b, { species_count: 1 }, LAB.GENESIS_DEFAULTS, E, V11E);
  const degrees = o.result.form.theme.degrees.slice(0, 6);
  for (const d of degrees) if (d < -7 || d > 7) throw new Error(`species ${x.id}: theme degree ${d}`);
  return { id: x.id, tier: x.tier, type: x.type, tonicPc: o.result.params.tonic_keynum % 12, mode: o.result.params.mode_id, degrees };
});
writeFileSync(new URL('../src/loot_species.js', import.meta.url), '// Generated by onchain/make_species.mjs: do not edit.\nexport const SPECIES = ' + JSON.stringify(recs) + ';\nexport const speciesRecord = (id) => SPECIES.find((s) => s.id === id);\n');
console.log(recs.map((r) => `${r.id} t${r.tier} f${r.type} pc${r.tonicPc} m${r.mode} [${r.degrees}]`).join('\n'));
