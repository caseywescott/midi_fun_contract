// Generate the compact Cairo table from the JS audition catalogue.
// node scripts/check_catalogue.mjs [--check]
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {CHECK_CATALOGUE} from '../offchain/beast-sound/src/sound_check_catalogue_data.js';
import {ESSENTIALS} from '../offchain/beast-sound/onchain/tinychip/essentials.mjs';
import {FAMILIES} from '../offchain/beast-sound/src/full_midi.js';

const PHRASES = ['incantation','spiral','veil','spring','flight','hunt','skitter','stomp','surge','yodel'];
function integer(value,min,max,label){
  if(!Number.isSafeInteger(value)||value<min||value>max)throw Error(`${label} must be an integer in ${min}..${max}`);
}
function degrees(values,length,min,max,label){
  if(!Array.isArray(values)||values.length!==length)throw Error(`${label} must contain ${length} degrees`);
  for(const value of values)integer(value,min,max,label);
}

// Validate before packing, so an invalid field cannot spill into its neighbour or truncate at runtime.
export function generateCatalogue(rows){
  if(!Array.isArray(rows)||rows.length!==75)throw Error('Check catalogue must contain exactly 75 ordered species');
  for(let i=0;i<rows.length;i++){
    const r=rows[i],label=`Check catalogue row ${i+1}`;
    if(!r||typeof r!=='object'||Array.isArray(r))throw Error(`${label} must be an object`);
    integer(r.species,1,75,`${label} species`);
    if(r.species!==i+1)throw Error(`${label} species must be ${i+1}`);
    if(typeof r.name!=='string'||!r.name.trim()||/[\r\n]/.test(r.name))throw Error(`${label} name must be a nonempty single line`);
    if(!PHRASES.includes(r.phrase))throw Error(`${label} has unsupported phrase`);
    integer(r.program,0,127,`${label} program`);
    if(!ESSENTIALS.includes(r.program))throw Error(`${label} has unsupported program ${r.program}`);
    const family=FAMILIES[Math.floor(i/25)];
    if(![...family.leads,...family.plucks].includes(r.program))throw Error(`${label} program ${r.program} is outside its species family bank`);
    if(![50,65].includes(r.mega))throw Error(`${label} mega must be 50 or 65`);
    if(![48,60].includes(r.register))throw Error(`${label} register must be 48 or 60`);
    integer(r.tempo_us,1,0xfffff,`${label} tempo_us`);
    if(![false,true,0,1].includes(r.pan))throw Error(`${label} pan must be boolean or 0/1`);
    integer(r.finalNotes,4,16,`${label} finalNotes`);
    degrees(r.head,16,-4,11,`${label} head`);
    degrees(r.response,16,-4,11,`${label} response`);
    degrees(r.held,2,0,15,`${label} held`);
    if(!Array.isArray(r.rhythm)||r.rhythm.length!==4)throw Error(`${label} rhythm must contain 4 durations`);
    for(const n of r.rhythm){integer(n,120,480,`${label} rhythm`);if(n%120)throw Error(`${label} rhythm durations must be multiples of 120`);}
    if(r.rhythm.reduce((a,b)=>a+b,0)!==960)throw Error(`${label} rhythm must total 960 ticks`);
  }
  const pack=xs=>xs.reduce((v,n,i)=>v+(BigInt(n+4)<<BigInt(i*4)),0n);
  const records=rows.map((r,i)=>{
    const rhythm=r.rhythm.reduce((v,n,i)=>v+(BigInt(n/120)<<BigInt(i*4)),0n);
    const held=BigInt(r.held[0]+16*r.held[1]);
    const meta=BigInt(r.program)+(BigInt(r.mega===65)<<7n)+(BigInt(r.register===48)<<8n)+(rhythm<<9n)+(held<<25n)+(BigInt(r.finalNotes)<<33n)+(BigInt(r.pan)<<38n)+(BigInt(r.tempo_us)<<39n);
    return `    (${meta}, ${pack(r.head)}, ${pack(r.response)})${i===74?'':','} // ${r.species} ${r.name}`;
  });
  return `//! Generated by scripts/check_catalogue.mjs from sound_check_catalogue_data.js.\n//! packed: program7, mega1, low-register1, rhythm16, held8, final-count5, pan1, tempo20.\nconst CHECKS: [(u64, u64, u64); 75] = [\n${records.join('\n')}\n];\n\n/// Original catalogue row, or the family's first row for future species.\npub fn catalogue_check(species: u32, family: u8) -> (u64, u64, u64) {\n    let index = if species <= 75 {\n        species - 1\n    } else {\n        family.into() * 25\n    };\n    *CHECKS.span().at(index)\n}\n`;
}

if(process.argv[1]&&pathToFileURL(resolve(process.argv[1])).href===import.meta.url){
  const text=generateCatalogue(CHECK_CATALOGUE);
  const path=new URL('../beasts/beast_composer/src/composition/check_catalogue_data.cairo',import.meta.url);
  if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==text)throw Error('Stale check catalogue');}else writeFileSync(path,text);
  console.log('Check catalogue:75 rows; all metadata and degree/rhythm packing valid');
}
