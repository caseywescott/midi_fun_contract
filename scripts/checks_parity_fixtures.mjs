// Writes the Sound Checks parity fixture (loot/loot_composer/src/checks_parity.cairo: #[ignore]d
// batches of five cases, each printing `CK i=<case> len=<bytes> hex=<file>`) and its case list
// (scripts/checks_parity_cases.json, read by checks_parity.mjs): every species' own take, mega off and
// on, and purchase takes (purchase_seed(p)).   node scripts/checks_parity_fixtures.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SPECIES } from '../offchain/loot-sound/src/loot_species.js';
import { soundCheckScore } from '../offchain/loot-sound/src/loot_checks.js';

const U64 = (1n << 64n) - 1n;
function purchaseSeed(n) { let x = BigInt(n) * 0x9e3779b97f4a7c15n & U64; x ^= x >> 30n; x = x * 0xbf58476d1ce4e5b9n & U64; x ^= x >> 27n; x = x * 0x94d049bb133111ebn & U64; return x ^ (x >> 31n); }
const cases = [];
const add = (sp, mega, p) => cases.push({ sp, mega, p, take: p ? purchaseSeed(p).toString() : '0' });
SPECIES.forEach((s, k) => add(s.id, k % 2 === 1, 0));
SPECIES.forEach((s, k) => add(s.id, k % 2 === 0, 0));
for (let p = 1; p <= 40; p++) add(SPECIES[(p * 7) % 30].id, p % 2 === 0, p);
const cov = {};
const see = (k, v) => { cov[k] = cov[k] || {}; cov[k][v] = (cov[k][v] || 0) + 1; };
for (const c of cases) {
  const sc = soundCheckScore(SPECIES.find((s) => s.id === c.sp), c.mega, BigInt(c.take));
  see('opening', sc.opening); see('close', sc.close); sc.drills.forEach((d) => see('drill', d)); see('gliss', sc.glPlan.length > 0);
}
console.log(JSON.stringify(cov));
const B = 5, batches = [];
for (let b = 0; b * B < cases.length; b++) {
  const body = cases.slice(b * B, b * B + B).map((c, k) => `    case(${b * B + k}, ${c.sp}, ${c.mega}, ${c.take});`).join('\n');
  batches.push(`#[test]\n#[ignore]\nfn checks_parity_${String(b + 1).padStart(2, '0')}() {\n${body}\n}\n`);
}
const src = `//! Sound Checks parity fixture: generated by scripts/checks_parity_fixtures.mjs, checked by
//! scripts/checks_parity.mjs (run with KIND=checks PREFIX=CK sh scripts/rounds_parity_cairo.sh). Do not edit.
use crate::checks::sound_check_smf_bytes;
use crate::rounds_parity::hex;

fn case(i: u32, species: u32, mega: bool, take: u64) {
    let bytes = sound_check_smf_bytes(species, mega, take);
    println!("CK i={} len={} hex={}", i, bytes.len(), hex(bytes.span()));
}

${batches.join('\n')}`;
writeFileSync(fileURLToPath(new URL('../loot/loot_composer/src/checks_parity.cairo', import.meta.url)), src);
writeFileSync(fileURLToPath(new URL('./checks_parity_cases.json', import.meta.url)), JSON.stringify(cases));
console.log(`${cases.length} cases in ${batches.length} batches`);
