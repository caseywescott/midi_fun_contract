import { musicalId } from '../offchain/loot-sound/src/loot_beasts.js';
// Writes the Rounds parity fixture (loot/loot_composer/src/rounds_parity.cairo: #[ignore]d batches of
// four cases, each printing `RD i=<case> len=<bytes> hex=<file>`) and its case list
// (scripts/rounds_parity_cases.json, read by rounds_parity.mjs). Cases: every species at seed 0 (mega
// off, then on with a day of drift), purchase seeds (purchase_seed(p)), drift days none, 9, 45, 100,
// 200, 290 (the lab's drift2 with block hashes, from the read-only Beast Sound v1.0.1 checkout).
//   node scripts/rounds_parity_fixtures.mjs [ref checkout]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SPECIES } from '../offchain/loot-sound/src/loot_species.js';
import { roundScore } from '../offchain/loot-sound/src/loot_rounds.js';

const REF = process.argv[2] || '/Volumes/Extreme SSD/Generative_Music_Series/midi_fun_contract-ref101';
const L = await import(REF + '/offchain/beast-sound/src/lab.js');
const U64 = (1n << 64n) - 1n;
export function purchaseSeed(n) { let x = BigInt(n) * 0x9e3779b97f4a7c15n & U64; x ^= x >> 30n; x = x * 0xbf58476d1ce4e5b9n & U64; x ^= x >> 27n; x = x * 0x94d049bb133111ebn & U64; return x ^ (x >> 31n); }
const DAYS = [0, 9, 45, 100, 200, 290];
const driftOf = (id, day) => (day ? L.drift2({ id: musicalId(id), prefix: 0, suffix: 0 }, day, L.dayAnchor()) : null);

const cases = [];
const add = (sp, mega, p, day) => cases.push({ sp, mega, p, seed: p ? purchaseSeed(p).toString() : '0', day });
SPECIES.forEach((s, k) => add(s.id, false, 0, 0));
SPECIES.forEach((s, k) => add(s.id, true, 0, DAYS[1 + (k % 5)]));
for (let p = 1; p <= 36; p++) add(SPECIES[(p * 7) % 30].id, p % 2 === 0, p, DAYS[p % 6]);
for (let p = 37; p <= 48; p++) add(SPECIES[(p * 11) % 30].id, p % 3 === 0, p, DAYS[(p * 5) % 6]);
// rarer modes (Locrian, Dorian #4): the first purchases that pick them
for (const want of [6, 26]) {
  let n = 0;
  for (let p = 49; n < 4 && p < 2000; p++) {
    const sp = SPECIES[(p * 13) % 30];
    if (roundScore(sp, false, purchaseSeed(p), null).mode === want) { add(sp.id, n % 2 === 1, p, DAYS[(n * 2 + 1) % 6]); n++; }
  }
}

// coverage of what the cases exercise
const cov = {};
const see = (k, v) => { cov[k] = cov[k] || {}; cov[k][v] = (cov[k][v] || 0) + 1; };
for (const c of cases) {
  const sp = SPECIES.find((s) => s.id === c.sp), d = driftOf(c.sp, c.day), sc = roundScore(sp, c.mega, BigInt(c.seed), d);
  see('meter', sc.meter); see('mode', sc.mode); see('hr', sc.hr); see('K', sc.K); see('epKind', sc.epKind); see('art', sc.art);
  see('bass', sc.bass.length > 0); see('perc', sc.perc.length > 0); see('gliss', sc.gliss.length > 0);
  see('graces', sc.voices.some((v) => v.notes.some((n) => n.grace)));
  if (d) { see('dayKnob', d.dayKnob); see('rhythm', d.rhythm !== null); see('rotate', d.rotate !== null); }
}
console.log(JSON.stringify(cov));

const felt = (x) => (x === null ? 'Option::None' : `Option::Some(0x${BigInt(x).toString(16)})`);
const B = 4, batches = [];
for (let b = 0; b * B < cases.length; b++) {
  const body = cases.slice(b * B, b * B + B).map((c, k) => {
    const i = b * B + k, d = driftOf(c.sp, c.day);
    const dr = d ? `Option::Some(Drift { rhythm: ${felt(d.rhythm)}, rotate: ${felt(d.rotate)}, day_knob: ${d.dayKnob}, delta_bpm: ${d.delta}, day: ${d.day} })` : 'Option::None';
    return `    case(${i}, ${c.sp}, ${c.mega}, ${c.seed}, ${dr});`;
  }).join('\n');
  batches.push(`#[test]\n#[ignore]\nfn rounds_parity_${String(b + 1).padStart(2, '0')}() {\n${body}\n}\n`);
}
// one case per test, no printing but the length: snforge's l2_gas per test is the gas of one Round
const gas = cases.map((c, i) => {
  const d = driftOf(c.sp, c.day);
  const dr = d ? `Option::Some(Drift { rhythm: ${felt(d.rhythm)}, rotate: ${felt(d.rotate)}, day_knob: ${d.dayKnob}, delta_bpm: ${d.delta}, day: ${d.day} })` : 'Option::None';
  return `#[test]\n#[ignore]\nfn rounds_gas_${String(i).padStart(3, '0')}() {\n    let n = round_smf_bytes(${c.sp}, ${c.mega}, ${c.seed}, ${dr}).len();\n    assert(n > 0, 'empty');\n}\n`;
});
const src = `//! Rounds parity fixture: generated by scripts/rounds_parity_fixtures.mjs, checked by
//! scripts/rounds_parity.mjs (run with scripts/rounds_parity_cairo.sh). Do not edit.
use beast_composer::composition::drift::Drift;
use crate::rounds::round_smf_bytes;

pub fn hex(bytes: Span<u8>) -> ByteArray {
    let digits: ByteArray = "0123456789abcdef";
    let mut out: ByteArray = "";
    for b in bytes {
        out.append_byte(digits.at((*b / 16).into()).unwrap());
        out.append_byte(digits.at((*b % 16).into()).unwrap());
    }
    out
}

fn case(i: u32, species: u32, mega: bool, seed: u64, drift: Option<Drift>) {
    let bytes = round_smf_bytes(species, mega, seed, drift);
    println!("RD i={} len={} hex={}", i, bytes.len(), hex(bytes.span()));
}

${batches.join('\n')}
${gas.join('\n')}`;
writeFileSync(fileURLToPath(new URL('../loot/loot_composer/src/rounds_parity.cairo', import.meta.url)), src);
writeFileSync(fileURLToPath(new URL('./rounds_parity_cases.json', import.meta.url)), JSON.stringify(cases, null, 0));
console.log(`${cases.length} cases in ${batches.length} batches`);
